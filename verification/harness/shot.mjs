import { chromium } from 'playwright-core';
const [base, prefix] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const pg = await ctx.newPage();
const errs = []; pg.on('console', m => { if (m.type() === 'error') errs.push(m.text()); }); pg.on('pageerror', e => errs.push(String(e)));
await pg.goto(base + '/products/the-ashby-quarter-zip', { waitUntil: 'networkidle' });
await pg.waitForTimeout(500);
await pg.screenshot({ path: `${prefix}-top.png` });
const info = await pg.evaluate(() => {
  const r = (s) => { const e = document.querySelector(s); if (!e) return null; const b = e.getBoundingClientRect(); return { top: Math.round(b.top), bottom: Math.round(b.bottom), h: Math.round(b.height) }; };
  const thumbs = [...document.querySelectorAll('.gallery-thumb img')].map(i => ({ src: i.getAttribute('src'), loaded: i.complete && i.naturalWidth > 0, w: Math.round(i.getBoundingClientRect().width) }));
  return { h1: r('.product-info h1'), price: r('[data-price-wrap]'), addRow: r('.add-row'), sticky: r('.sticky-atc'), thumbs: r('.gallery-thumbs'), thumbImgs: thumbs };
});
console.log(JSON.stringify(info, null, 1));
await pg.locator('.gallery-thumbs').scrollIntoViewIfNeeded().catch(()=>{});
